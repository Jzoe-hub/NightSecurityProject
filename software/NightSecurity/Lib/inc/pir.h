/**********************************************************************
 * 文件名称： pir.h
 * 功能描述： HC-SR501 人体红外传感器驱动头文件
 * 硬件连接： OUT → PA8 (GPIO 浮空输入, CubeMX 标签: PIR_OUT)
 * 说    明： 模块输出高电平=有人, 低电平=无人, 驱动层只封装读取函数
 * 使用示例： if (PIR_Read()) { ...有人... }
 ***********************************************************************/
#ifndef __PIR_H
#define __PIR_H

#include <stdint.h>

/**********************************************************************
 * 函数名称： PIR_Read
 * 功能描述： 读取 PIR 传感器输出电平
 * 返 回 值： 1 = 检测到人体, 0 = 无人
 ***********************************************************************/
uint8_t PIR_Read(void);

#endif /* __PIR_H */
