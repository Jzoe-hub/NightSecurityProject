/**********************************************************************
 * 文件名称： dht11.h
 * 功能描述： DHT11 数字温湿度传感器驱动头文件
 * 硬件连接： DATA → PA12 (开漏输出 + 外部上拉, CubeMX 标签: DHT11_DATE)
 * 说    明： 传感器读取周期 ≥2 秒, 不可频繁读取
 ***********************************************************************/
#ifndef __DHT11_H
#define __DHT11_H

/**********************************************************************
 * 函数名称： DHT11_Init
 * 功能描述： DHT11 初始化, 将 DATA 引脚置高进入空闲状态
 ***********************************************************************/
void DHT11_Init(void);

/**********************************************************************
 * 函数名称： DHT11_Read
 * 功能描述： 读取一次 DHT11 的温度和湿度
 * 输出参数： hum  — 湿度值 (%RH, 整数)
 *            temp — 温度值 (℃, 整数)
 * 返 回 值： 0 = 成功, -1 = 失败（无应答 / 校验错）
 * 说    明： DHT11 读取周期至少 2 秒, 每次调用间隔不足会出校验错
 ***********************************************************************/
int DHT11_Read(int *hum, int *temp);

#endif /* __DHT11_H */
