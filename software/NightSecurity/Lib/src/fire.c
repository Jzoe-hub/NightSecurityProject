/**********************************************************************
 * 文件名称： fire.c
 * 功能描述： 火焰传感器（AO 模拟口） — ADC 原始值到火焰强度的纯换算
 * 来    源： 辰哥单片机设计 (Bilibili/CSDN), SPL→HAL 移植, 公式保留
 * 说    明： 1. GPIO/ADC 初始化 → CubeMX 已经做了
 *           2. 主动读 ADC / 延时 → TIM3 + DMA 硬件自动采样
 *           3. 多次均值滤波 → 由 task_sensor.c 按任务周期做
 *           4. AO 模拟口：ADC 取反得火焰强度, DO 数字口：GPIO 直读得开关量
 ***********************************************************************/
#include "fire.h"
#include "stm32f1xx_hal.h"

/**********************************************************************
 * 函数名称： Fire_GetIntensity
 * 功能描述： AO口：将 ADC 12 位原始码值换算为火焰强度。
 *           火焰传感器（红外光电管）：火焰越强 → 红外辐射越多 →
 *           传感器电阻越小 → AO 电压越高 → ADC 码值越大。
 *           取反后得到"火焰强度"：0 = 无火, 4095 = 极强火焰。
 * 输入参数： raw — DMA 缓冲区 [FIRE_ADC_INDEX] 处的原始值 (0~4095)
 * 输出参数： 无
 * 返 回 值： 火焰强度 (0~4095)
 ***********************************************************************/
uint16_t Fire_GetIntensity(uint16_t raw)
{
	return 4095 - raw;   //真实火焰大→raw小→火焰强度大。
}

/**********************************************************************
 * 函数名称： Fire_IsDetected
 * 功能描述： 读取火焰传感器 DO 数字口电平。
 *           DO 输出为模块板载比较器结果, 阈值可通过模块电位器调节。
 * 输入参数： 无
 * 输出参数： 无
 * 返 回 值： 0 = 检测到火焰, 1 = 无火焰
 ***********************************************************************/
uint8_t Fire_IsDetected(void)
{
	return (uint8_t)HAL_GPIO_ReadPin(FIRE_DO_PORT, FIRE_DO_PIN);   // 0=有火, 1=无火
}
