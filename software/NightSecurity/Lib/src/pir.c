/**********************************************************************
 * 文件名称： pir.c
 * 功能描述： HC-SR501 人体红外传感器驱动
 * 来    源： 辰哥单片机设计 (Bilibili/CSDN), SPL→HAL 移植
 * 硬件连接： OUT → PA8 (GPIO 浮空输入)
 * 说    明： 1. GPIO 初始化 → CubeMX 已配置 PA8 为浮空输入
 *           2. HC-SR501 模块自带延时/灵敏度调节, 输出为开关量
 ***********************************************************************/
#include "pir.h"
#include "stm32f1xx_hal.h"

/* ---- PIR 引脚定义 ---- */
#define PIR_PORT            GPIOA
#define PIR_PIN             GPIO_PIN_8

/**********************************************************************
 * 函数名称： PIR_Read
 * 功能描述： 读取 PIR 传感器输出电平
 *           高电平 = 检测到人体红外, 低电平 = 无人
 * 返 回 值： 1 = 有人, 0 = 无人
 ***********************************************************************/
uint8_t PIR_Read(void)
{
	return (HAL_GPIO_ReadPin(PIR_PORT, PIR_PIN) == GPIO_PIN_SET) ? 1 : 0;
}
