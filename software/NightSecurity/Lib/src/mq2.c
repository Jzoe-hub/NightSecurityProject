/**********************************************************************
 * 文件名称： mq2.c
 * 功能描述： MQ-2 烟雾/可燃气体传感器 — ADC 原始值到 ppm 的纯换算实现
 * 来    源： 辰哥单片机设计 (Bilibili/CSDN) + CSDN qq_53931105, SPL→HAL 移植
 * 说    明： 本文件"刻意不做"的三件事：
 *           1. GPIO/ADC 初始化 → CubeMX 生成的 MX_ADC1_Init() 已经做了
 *           2. 主动读 ADC / 延时 → TIM3 + DMA 硬件自动采样
 *           3. 多次均值滤波 → 由 task_sensor.c 按任务周期做
 ***********************************************************************/
#include "mq2.h"
#include <math.h>

/**********************************************************************
 * 函数名称： MQ2_RawToPPM
 * 功能描述： 将 ADC 12 位原始码值换算为浓度。换算三步：
 *           1. 码值→电压：ADC 以 3.3V 为满量程, 共 4096 个刻度
 *           2. 电压→电阻：5V 经 RS、RL 串联分压, AO 即 RL 上的电压,
 *              用分压公式反推 RS（RL=2kΩ, 对应板上 202 丝印）
 *           3. 电阻→浓度：幂函数拟合 RS/R0—ppm 曲线
 * 输入参数： raw — DMA 缓冲区 [MQ2_ADC_INDEX] 处的原始值 (0~4095)
 * 输出参数： 无
 * 返 回 值： 浓度 (ppm)；电压过低时返回 0（未预热 / 未接线）
 * 说    明： 1. 模块供 5V 时 AO 可能超过 3.3V, 超量程会被 ADC 削顶读成 4095
 *           2. R0=6.64 为参考代码洁净空气标定值, 需在通风处预热后实测替换
 ***********************************************************************/
float MQ2_RawToPPM(uint16_t raw)
{
	float vol = raw * 3.3f / 4096.0f;
	if (vol < 0.01f)                   // 防除零：传感器未预热或未接线
	{
		return 0.0f;
	}
	float RS = (5.0f - vol) / (vol * 0.5f);   // RL=2kΩ, (5-Vol)/(Vol×0.5)
	float R0 = 6.64f;                         // 洁净空气标定电阻
	/* Rs/R0 = 11.5428 × ppm^(-0.6549), 即 ppm = (11.5428×R0/RS)^(1/0.6549) */
	return powf(11.5428f * R0 / RS, 0.6549f);
}

