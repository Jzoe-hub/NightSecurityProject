/**********************************************************************
 * 文件名称： voice.c
 * 功能描述： JQ8900 语音模块驱动 (IO 脉冲触发模式)
 * 硬件连接： IO1→PB6, IO2→PB7, IO3→PB3, IO4→PB4 (推挽输出, 默认高)
 *           BUSY→PB12 (GPIO 输入, 高=播放中)
 * 来    源： 小暗XiaoAn (CSDN), SPL→HAL 移植
 * 说    明： 1. GPIO 初始化 → CubeMX 已全部配置
 *           2. 触发方式: 拉低 200ms→拉高, JQ8900 检测下降沿后播放
 *           3. 曲目预先存入 JQ8900 的 TF 卡, 与 IO 口对应
 ***********************************************************************/
#include "voice.h"

/* ---- 内部：通用 IO 脉冲触发 ---- */
static void voice_trigger(GPIO_TypeDef *port, uint16_t pin)
{
	HAL_GPIO_WritePin(port, pin, GPIO_PIN_RESET);      /* 拉低        */
	HAL_Delay(VOICE_TRIGGER_MS);                         /* 保持 200ms  */
	HAL_GPIO_WritePin(port, pin, GPIO_PIN_SET);         /* 拉高恢复    */
}

/* ==================== 公开接口 ==================== */

/**********************************************************************
 * 函数名称： Voice_IO1_Trigger
 * 功能描述： 触发 IO1 对应曲目（预录火灾报警语音）
 ***********************************************************************/
void Voice_IO1_Trigger(void)
{
	voice_trigger(VOICE_IO1_PORT, VOICE_IO1_PIN);
}

/**********************************************************************
 * 函数名称： Voice_IO2_Trigger
 * 功能描述： 触发 IO2 对应曲目（预录入入侵报警语音）
 ***********************************************************************/
void Voice_IO2_Trigger(void)
{
	voice_trigger(VOICE_IO2_PORT, VOICE_IO2_PIN);
}

/**********************************************************************
 * 函数名称： Voice_IO3_Trigger
 * 功能描述： 触发 IO3 对应曲目
 ***********************************************************************/
void Voice_IO3_Trigger(void)
{
	voice_trigger(VOICE_IO3_PORT, VOICE_IO3_PIN);
}

/**********************************************************************
 * 函数名称： Voice_IO4_Trigger
 * 功能描述： 触发 IO4 对应曲目
 ***********************************************************************/
void Voice_IO4_Trigger(void)
{
	voice_trigger(VOICE_IO4_PORT, VOICE_IO4_PIN);
}

/**********************************************************************
 * 函数名称： Voice_IsBusy
 * 功能描述： 读取 BUSY 引脚, 判断是否正在播放
 * 返 回 值： 1=播放中, 0=空闲
 ***********************************************************************/
uint8_t Voice_IsBusy(void)
{
	return (HAL_GPIO_ReadPin(VOICE_BUSY_PORT, VOICE_BUSY_PIN) == GPIO_PIN_SET) ? 1 : 0;
}
